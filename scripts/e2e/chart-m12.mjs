import { chromium } from "playwright";
const API = process.env.E2E_API ?? "http://localhost:8020", WEB = process.env.E2E_WEB ?? "http://localhost:3000";
const email = `m12c-${Date.now()}@example.com`, password = "supersecret1";
const post = async (p, b, t) => (await fetch(API + p, { method: "POST", headers: { "Content-Type": "application/json", ...(t ? { Authorization: `Bearer ${t}` } : {}) }, body: JSON.stringify(b) })).json();
await post("/auth/register", { email, password });
const { access_token: t } = await post("/auth/login", { email, password });
await post("/accounts", { name: "Corrente", type: "checking", opening_balance: "1000" }, t);
await post("/assets", { name: "Casa", kind: "real_estate", current_value: "200000", valued_at: "2026-07-15" }, t);
const b = await chromium.launch();
const page = await b.newPage({ viewport: { width: 1280, height: 900 } });
await page.goto(WEB + "/login");
await page.fill("#email", email); await page.fill("#password", password);
await page.getByRole("button", { name: "Entrar" }).click();
await page.waitForURL("**/accounts");
await page.goto(WEB + "/net-worth");
await page.waitForSelector("svg.recharts-surface", { timeout: 15000 });
await page.waitForTimeout(1500);
console.log("OK  gráfico renderizado");
await page.screenshot({ path: "m12-4-grafico.png", fullPage: true });
await b.close();
